using System.Collections.Generic;
using UnityEngine;

namespace JLPTQuest
{
    /*
        Everything the importer made, in one place.
        The game only ever reads from here, never from the sheet, so builds work offline and on WebGL.
        Regenerated by Tools > JLPT Quest > Sync From Google Sheet, so hand edits get wiped.
    */
    public class ContentDatabase : ScriptableObject
    {
        public List<QuestionSet> lessons = new List<QuestionSet>();
        public List<EnemyData> enemies = new List<EnemyData>();
        public List<StageData> stages = new List<StageData>();
        public List<GrammarData> grammar = new List<GrammarData>(); //In teaching order, as on the sheet
        public List<WordData> words = new List<WordData>();
        public string lastImport;

        private Dictionary<string, QuestionData> questionLookup;
        private Dictionary<string, EnemyData> enemyLookup;
        private Dictionary<string, StageData> stageLookup;
        private Dictionary<int, QuestionSet> lessonLookup;
        private Dictionary<string, GrammarData> grammarLookup;

        void OnEnable()
        {
            questionLookup = null; //Rebuilt lazily the first time something asks
        }

        public QuestionData GetQuestion(string id)
        {
            EnsureLookups();
            return id != null && questionLookup.TryGetValue(id, out QuestionData question) ? question : null;
        }

        public EnemyData GetEnemy(string id)
        {
            EnsureLookups();
            return id != null && enemyLookup.TryGetValue(id, out EnemyData enemy) ? enemy : null;
        }

        public StageData GetStage(string id)
        {
            EnsureLookups();
            return id != null && stageLookup.TryGetValue(id, out StageData stage) ? stage : null;
        }

        public GrammarData GetGrammar(string id)
        {
            EnsureLookups();
            return !string.IsNullOrEmpty(id) && grammarLookup.TryGetValue(id, out GrammarData point) ? point : null;
        }

        //A lesson's grammar points in teaching order
        public List<GrammarData> GrammarFor(int lesson)
        {
            return grammar.FindAll(point => point.lesson == lesson);
        }

        public List<WordData> WordsFor(int lesson)
        {
            return words.FindAll(word => word.lesson == lesson);
        }

        public QuestionSet GetLesson(int lesson)
        {
            EnsureLookups();
            return lessonLookup.TryGetValue(lesson, out QuestionSet set) ? set : null;
        }

        public IEnumerable<QuestionData> AllQuestions()
        {
            foreach (QuestionSet set in lessons)
            {
                if (set == null) continue;
                foreach (QuestionData question in set.questions)
                    yield return question;
            }
        }

        //The importer calls this after it swaps the content out
        public void RebuildLookups()
        {
            questionLookup = new Dictionary<string, QuestionData>();
            lessonLookup = new Dictionary<int, QuestionSet>();
            foreach (QuestionSet set in lessons)
            {
                if (set == null) continue;
                lessonLookup[set.lesson] = set;
                foreach (QuestionData question in set.questions)
                    questionLookup[question.id] = question;
            }

            enemyLookup = new Dictionary<string, EnemyData>();
            foreach (EnemyData enemy in enemies)
                enemyLookup[enemy.id] = enemy;

            stageLookup = new Dictionary<string, StageData>();
            foreach (StageData stage in stages)
                stageLookup[stage.id] = stage;

            grammarLookup = new Dictionary<string, GrammarData>();
            foreach (GrammarData point in grammar)
                grammarLookup[point.id] = point;
        }

        private void EnsureLookups()
        {
            if (questionLookup == null) RebuildLookups();
        }
    }
}
